#!/usr/bin/env python3
"""Verify the firmware PID coefficients against the colleague's MATLAB work.

The heading controller is generated by ``heading_conversion.m`` from
``Motor_model_param.m``:

    C(s) = Kph * (head_tau_d*s + 1) / (head_alpha*head_tau_d*s + 1)
    Ts = 0.001 s, c2d(..., 'tustin')

The per-wheel velocity PI uses the same Tustin rule at Ts = 1 ms:

    C(z) = Kp + Ki*Ts/2 * (z + 1)/(z - 1)

Run from the project root with any Python 3 interpreter (standard library
only):

    python3 tests/motion_host/verify_controller_coeffs.py
"""

import csv
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PARAM = ROOT / "Motor_model_param.m"
CONVERSION = ROOT / "heading_conversion.m"
FIRMWARE = ROOT / "src" / "src" / "basebot_6.ino"
UIMU = ROOT / "src" / "src" / "uimu2.cpp"
MOTOR_CSV = ROOT / "week06" / "basebot_motor_parameters.csv"
ROBOT_DEFAULTS = ROOT / "week06" / "robot_model_defaults.m"

TOL = 1e-6


def parse_scalar(text, name, path):
    match = re.search(
        rf"(?<![A-Za-z0-9_]){re.escape(name)}\s*=\s*([-+0-9.eE]+)[fF]?\s*;",
        text)
    if match is None:
        raise SystemExit(f"could not find {name} in {path}")
    return float(match.group(1))


def parse_coeffs(text, name):
    match = re.search(
        rf"{re.escape(name)}\s*=\s*\{{([^}}]*)\}}\s*;", text, re.DOTALL)
    if match is None:
        raise SystemExit(f"could not find {name} in {FIRMWARE}")
    values = []
    for item in match.group(1).split(","):
        item = item.strip().rstrip("fF")
        if item:
            values.append(float(item))
    if len(values) != 5:
        raise SystemExit(f"{name}: expected 5 values, got {values}")
    return values


def tustin_heading(kph, tau_d, alpha, ts):
    # Same algebra as heading_conversion.m: substitute
    # s = 2/Ts * (z-1)/(z+1) and normalize by the denominator's a0.
    n0 = 2.0 * tau_d / ts + 1.0
    n1 = 1.0 - 2.0 * tau_d / ts
    d0 = 2.0 * alpha * tau_d / ts + 1.0
    d1 = 1.0 - 2.0 * alpha * tau_d / ts
    return [kph * n0 / d0, kph * n1 / d0, 0.0, d1 / d0, 0.0]


def tustin_pi(kp, ki, ts):
    return [kp + ki * ts / 2.0, -kp + ki * ts / 2.0, 0.0, -1.0, 0.0]


def check_geometry(firmware_text, param_text):
    """Print the firmware/colleague/week06 geometry. This is a warning only:
    the physical gear ratio, wheel radius and track width must be measured
    before changing the KF gains or comparing linear speed."""
    fw_gear = parse_scalar(firmware_text, "gear", FIRMWARE)
    fw_radius = parse_scalar(firmware_text, "wheelRadius", FIRMWARE)
    fw_base = parse_scalar(firmware_text, "wheelBase", FIRMWARE)

    col_gear = parse_scalar(param_text, "gear", PARAM)
    col_radius = parse_scalar(param_text, "wrad", PARAM)
    col_base = parse_scalar(param_text, "B", PARAM)

    with open(MOTOR_CSV, newline="") as f:
        row = next(csv.DictReader(f))
    csv_gear = float(row["gear"])
    csv_radius = float(row["wheelRadius"])

    defaults_text = ROBOT_DEFAULTS.read_text()
    match = re.search(r"'trackWidth'\s*,\s*([-+0-9.eE]+)", defaults_text)
    week06_base = float(match.group(1)) if match else float("nan")

    print("\nGeometry (warning only; confirm physically before changing):")
    print("%-12s %10s %12s %12s %12s" %
          ("quantity", "firmware", "colleague", "week06", "match"))
    rows = [
        ("gear", fw_gear, col_gear, csv_gear),
        ("wheelRadius", fw_radius, col_radius, csv_radius),
        ("wheelBase", fw_base, col_base, week06_base),
    ]
    different = False
    for name, fw, col, wk in rows:
        same = (math.isclose(fw, col, rel_tol=0.0, abs_tol=1e-9) and
                math.isclose(fw, wk, rel_tol=0.0, abs_tol=1e-9))
        different = different or not same
        print("%-12s %10.6g %12.6g %12.6g %12s" %
              (name, fw, col, wk, "yes" if same else "NO"))
    if different:
        print("WARNING: firmware geometry differs from Motor_model_param.m "
              "and/or week06. Confirm the physical values before changing the "
              "KF gains; see src/src/KF_specification.md section 9.")


def check_vector(name, expected, actual, failures):
    labels = ["b0", "b1", "b2", "a1", "a2"]
    for label, want, got in zip(labels, expected, actual):
        ok = math.isclose(want, got, rel_tol=0.0, abs_tol=TOL)
        print("%-6s %-8s expected % .9f  firmware % .9f  %s" %
              (name, label, want, got, "OK" if ok else "MISMATCH"))
        if not ok:
            failures.append(f"{name}.{label}: expected {want}, got {got}")


def main():
    param_text = PARAM.read_text()
    conv_text = CONVERSION.read_text()
    firmware_text = FIRMWARE.read_text()
    uimu_text = UIMU.read_text()

    kph = parse_scalar(param_text, "Kph", PARAM)
    tau_d = parse_scalar(param_text, "head_tau_d", PARAM)
    alpha = parse_scalar(param_text, "head_alpha", PARAM)
    kp_left = parse_scalar(param_text, "Kp_vel_left", PARAM)
    ki_left = parse_scalar(param_text, "Ki_vel_left", PARAM)
    kp_right = parse_scalar(param_text, "Kp_vel_right", PARAM)
    ki_right = parse_scalar(param_text, "Ki_vel_right", PARAM)

    ts = parse_scalar(conv_text, "Ts", CONVERSION)
    sample_time_us = parse_scalar(firmware_text, "sampleTimeUs", FIRMWARE)
    failures = []

    if not math.isclose(ts, sample_time_us * 1e-6, rel_tol=0.0, abs_tol=1e-12):
        failures.append(
            f"time step mismatch: heading_conversion.m Ts={ts}, "
            f"firmware sampleTimeUs={sample_time_us}")
    if "tustin" not in conv_text.lower():
        failures.append("heading_conversion.m does not use c2d(..., 'tustin')")

    heading_expected = tustin_heading(kph, tau_d, alpha, ts)
    left_expected = tustin_pi(kp_left, ki_left, ts)
    right_expected = tustin_pi(kp_right, ki_right, ts)

    heading_actual = parse_coeffs(firmware_text, "heading_coeffs")
    left_actual = parse_coeffs(firmware_text, "left_wheel_coeffs")
    right_actual = parse_coeffs(firmware_text, "right_wheel_coeffs")

    print("Controller coefficient check (Ts = %.6f s)" % ts)
    print("Heading: Kph=%.4g head_tau_d=%.4g head_alpha=%.4g" %
          (kph, tau_d, alpha))
    check_vector("heading", heading_expected, heading_actual, failures)
    check_vector("wheel-L", left_expected, left_actual, failures)
    check_vector("wheel-R", right_expected, right_actual, failures)

    check_geometry(firmware_text, param_text)

    for name in ("KpLV", "KpLT", "Lim_VU", "Lim_VL", "Lim_TU", "Lim_TL"):
        want = parse_scalar(param_text, name, PARAM)
        got = parse_scalar(firmware_text, name.replace("Lim_", "Lim_"), FIRMWARE)
        ok = math.isclose(want, got, rel_tol=0.0, abs_tol=TOL)
        print("%-6s expected % .6f  firmware % .6f  %s" %
              (name, want, got, "OK" if ok else "MISMATCH"))
        if not ok:
            failures.append(f"{name}: expected {want}, got {got}")

    divider_match = re.search(
        r"MAG_UPDATE_DIVIDER\s*=\s*(\d+)\s*;", uimu_text)
    if divider_match is None:
        failures.append("MAG_UPDATE_DIVIDER not found in uimu2.cpp")
    else:
        divider = int(divider_match.group(1))
        expected_divider = 100  # 10 Hz at the 1 kHz tick
        print("mag update divider expected %d  firmware %d  %s" %
              (expected_divider, divider,
               "OK" if divider == expected_divider else "MISMATCH"))
        if divider != expected_divider:
            failures.append(
                f"MAG_UPDATE_DIVIDER: expected {expected_divider}, got {divider}")

    if failures:
        print("\nFAIL:")
        for failure in failures:
            print("  - " + failure)
        return 1
    print("\nPASS: firmware coefficients match the colleague's MATLAB work.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
